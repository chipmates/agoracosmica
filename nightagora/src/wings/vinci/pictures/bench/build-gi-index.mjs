function main() {
  const args = process.argv.slice(2), options = {}
  let check = false, dryRun = false
  for (let i = 0; i < args.length; i++) {
    const arg = args[i]
    if (arg === '--check') check = true
    else if (arg === '--dry-run') dryRun = true
    else if (['--config', '--data', '--out'].includes(arg)) {
      if (!args[i + 1]) throw Error(`Missing ${arg} value`)
      options[arg.slice(2)] = args[++i]
    } else throw Error(`Unknown GI index option ${arg}`)
  }
  if (check && dryRun) throw Error('Choose --check or --dry-run')
  const result = renderBenchGIIndex(options)
  if (check) {
    if (!existsSync(result.output) || readFileSync(result.output, 'utf8') !== result.source)
      throw Error('Stale or missing GI index; run node src/wings/vinci/pictures/bench/build-gi-index.mjs')
  } else if (!dryRun) writeFileSync(result.output, result.source)
  console.log(JSON.stringify({ mode: check ? 'checked' : dryRun ? 'verified without writing' : 'generated',
    output: relative(app, result.output), sourceSha256: hash(result.source),
    segments: result.segments.map(row => ({ segment: row.segment, expected: row.expected,
      room: row.room, residentMiB: row.residentMiB })) }, null, 2))
}
if (process.argv[1] && resolve(process.argv[1]) === here) {
  try { main() } catch (error) { console.error(error instanceof Error ? error.message : error); process.exitCode = 1 }
}
